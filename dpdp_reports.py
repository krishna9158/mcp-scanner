def generate_dpdp_csv_export(org_id: str, scope: str = "full") -> str:
    d = _gather_org_report_data(org_id)
    buf = io.StringIO()
    w = csv.writer(buf)

    if scope == "vendors":
        w.writerow(["Vendor ID", "Name", "Service", "Data Shared", "Location", "Agreement Status", "Expiry", "Risk Rating"])
        for v in d["vendors"]:
            w.writerow([v.get("id"), v.get("name"), v.get("service"), v.get("personal_data_processed"), v.get("storage_location"), v.get("dpa_status"), v.get("agreement_expiry"), v.get("risk_rating")])
        return buf.getvalue()

    if scope == "requests":
        w.writerow(["Request ID", "Type", "Requester", "Contact", "Status", "Owner", "Received", "SLA Date"])
        for r in d["requests"]:
            w.writerow([r.get("id"), r.get("type"), r.get("principal_name"), r.get("principal_contact"), r.get("status"), r.get("assigned_to"), r.get("received_at"), r.get("sla_deadline")])
        return buf.getvalue()

    if scope == "retention":
        w.writerow(["Schedule ID", "Category", "Purpose", "Period (Years)", "Legal Exception / Basis", "Deletion Method", "Owner"])
        for r in d["retention"]:
            w.writerow([r.get("id"), r.get("category"), r.get("purpose"), r.get("period_years"), r.get("statutory_basis"), r.get("deletion_method"), r.get("owner", "Privacy Lead")])
        return buf.getvalue()

    if scope == "inventory":
        return dpdp_store.export_inventory_csv(org_id)

    # Full unified operational CSV register
    w.writerow(["Section", "ID", "Item / Title", "Category / Type", "Status / Basis", "Details", "Updated / Timestamp"])
    for i in d["inventory"]:
        w.writerow(["Customer Data List", i.get("id"), i.get("category"), i.get("department"), i.get("legal_basis"), i.get("purpose"), i.get("updated_at")])
    for v in d["vendors"]:
        w.writerow(["Companies Shared With", v.get("id"), v.get("name"), v.get("service"), v.get("dpa_status"), v.get("storage_location"), v.get("created_at")])
    for r in d["requests"]:
        w.writerow(["Customer Privacy Requests", r.get("id"), r.get("principal_name"), r.get("type"), r.get("status"), r.get("description"), r.get("received_at")])
    for ret in d["retention"]:
        w.writerow(["Retention Rules", ret.get("id"), ret.get("category"), f"{ret.get('period_years', 0)} yrs", ret.get("status"), ret.get("deletion_method"), ret.get("created_at")])
    for ev in d["evidence"]:
        w.writerow(["Evidence Vault", ev.get("id"), ev.get("title"), ev.get("control_id"), ev.get("status"), ev.get("filename"), ev.get("uploaded_at")])
    for inc in d["incidents"]:
        w.writerow(["Privacy Incidents", inc.get("id"), inc.get("title"), inc.get("severity"), inc.get("board_notification_status"), inc.get("containment_status"), inc.get("detected_at")])
    return buf.getvalue()


def generate_dpdp_evidence_bundle_zip(org_id: str) -> bytes:
    """Packages PDF report, CSV registers, Privacy Notices, and physical Evidence files into a downloadable ZIP."""
    d = _gather_org_report_data(org_id)
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("00_TrustAudit_DPDP_Readiness_Summary.pdf", generate_dpdp_pdf_report(org_id))
        zf.writestr("00_TrustAudit_DPDP_Readiness_Summary.html", generate_dpdp_html_report(org_id).encode("utf-8"))
        zf.writestr("01_Customer_Data_List.csv", generate_dpdp_csv_export(org_id, "inventory").encode("utf-8"))
        zf.writestr("02_Vendors_and_Agreements.csv", generate_dpdp_csv_export(org_id, "vendors").encode("utf-8"))
        zf.writestr("03_Customer_Privacy_Requests.csv", generate_dpdp_csv_export(org_id, "requests").encode("utf-8"))
        zf.writestr("04_Retention_Rules.csv", generate_dpdp_csv_export(org_id, "retention").encode("utf-8"))

        for idx, notice in enumerate(d["notices"], 1):
            fname = sanitize_filename(f"notice_{idx}_{notice.get('version', 'v1')}.txt")
            zf.writestr(f"05_Privacy_Notices/{fname}", str(notice.get("content", "")).encode("utf-8"))

        manifest_items = []
        for ev in d["evidence"]:
            manifest_items.append({
                "id": ev.get("id"),
                "title": ev.get("title"),
                "control_id": ev.get("control_id"),
                "status": ev.get("status"),
                "filename": ev.get("filename"),
                "file_hash": ev.get("file_hash"),
                "uploaded_at": ev.get("uploaded_at"),
                "expiry_date": ev.get("expiry_date"),
                "physical_file_included": bool(ev.get("has_physical_file")),
            })
            raw, meta = dpdp_store.get_evidence_file_bytes(org_id, ev.get("id", ""))
            if raw and meta:
                safe = sanitize_filename(f"{ev.get('id')}_{meta.get('filename', 'file')}")
                zf.writestr(f"06_Uploaded_Evidence_Files/{safe}", raw)

        for lev in d["legacy_evidence"]:
            raw, meta = evidence_vault.read_evidence_file_bytes(lev.get("id", ""), org_id)
            manifest_items.append({
                "id": lev.get("id"),
                "title": lev.get("title"),
                "control_id": lev.get("control_id"),
                "status": lev.get("review_status") or lev.get("status"),
                "filename": (meta or {}).get("original_filename", ""),
                "file_hash": f"sha256:{(meta or {}).get('sha256', '')}" if meta else "",
                "physical_file_included": bool(raw),
            })
            if raw and meta:
                safe = sanitize_filename(f"{lev.get('id')}_{meta.get('original_filename', 'file')}")
                zf.writestr(f"06_Uploaded_Evidence_Files/{safe}", raw)

        manifest = {
            "company_name": d["company_name"],
            "org_id": org_id,
            "generated_at": d["generated_at"],
            "evidence_count": len(manifest_items),
            "items": manifest_items,
            "note": "Substantive DPDP Act duties (Sections 3-17) commence 13 May 2027. Verify counsel review for statutory filings.",
        }
        zf.writestr("Evidence_Bundle_Manifest.json", json.dumps(manifest, indent=2).encode("utf-8"))

    return out.getvalue()
