def _pdf_safe_text(text: Any) -> str:
    """Normalizes Unicode text cleanly into WinAnsi/ASCII-safe Type1 PDF strings."""
    s = str(text or "")
    replacements = {
        "\u20b9": "Rs. ",
        "\u2013": "-",
        "\u2014": "--",
        "\u2018": "'",
        "\u2019": "'",
        "\u201c": '"',
        "\u201d": '"',
        "\u2022": "*",
        "\u2192": "->",
        "\u2713": "[OK]",
        "\u2714": "[OK]",
        "\u2717": "[X]",
    }
    for k, v in replacements.items():
        s = s.replace(k, v)
    s = s.encode("latin-1", errors="replace").decode("latin-1")
    return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


class PurePythonPDFBuilder:
    """Builds multi-page A4 valid PDF 1.4 documents using built-in Type1 Helvetica fonts."""

    PAGE_W = 595
    PAGE_H = 842
    LEFT_MARGIN = 46
    TOP_Y = 792
    BOTTOM_Y = 54

    def __init__(self, doc_title: str) -> None:
        self.doc_title = _pdf_safe_text(doc_title)
        self.pages_cmds: List[List[str]] = []
        self.y = self.TOP_Y
        self._start_page()

    def _start_page(self) -> None:
        cmds: List[str] = [
            "0.08 0.14 0.25 rg",
            f"0 {self.PAGE_H - 34} {self.PAGE_W} 34 re f",
            "BT /F2 9 Tf 1 1 1 rg 46 819 Td (TrustAudit DPDP Readiness & Data Operations Report) Tj ET",
        ]
        self.pages_cmds.append(cmds)
        self.y = self.TOP_Y - 12

    def _ensure_space(self, needed: int = 24) -> None:
        if self.y - needed < self.BOTTOM_Y:
            self._start_page()

    def add_heading(self, title: str) -> None:
        self._ensure_space(34)
        self.y -= 8
        safe = _pdf_safe_text(title)
        self.pages_cmds[-1].append(
            f"BT /F2 13 Tf 0.08 0.22 0.45 rg {self.LEFT_MARGIN} {self.y} Td ({safe}) Tj ET"
        )
        self.y -= 6
        self.pages_cmds[-1].append(
            f"0.85 0.89 0.94 RG 0.8 w {self.LEFT_MARGIN} {self.y} m {self.PAGE_W - self.LEFT_MARGIN} {self.y} l S"
        )
        self.y -= 14

    def add_subheading(self, title: str) -> None:
        self._ensure_space(22)
        safe = _pdf_safe_text(title)
        self.pages_cmds[-1].append(
            f"BT /F2 10.5 Tf 0.12 0.16 0.24 rg {self.LEFT_MARGIN} {self.y} Td ({safe}) Tj ET"
        )
        self.y -= 15

    def add_paragraph(self, text: str, font_size: float = 9.5, indent: int = 0) -> None:
        width_chars = max(48, int((self.PAGE_W - 2 * self.LEFT_MARGIN - indent) / (font_size * 0.52)))
        for raw_line in str(text or "").splitlines() or [""]:
            wrapped = textwrap.wrap(raw_line, width=width_chars) or [""]
            for line in wrapped:
                self._ensure_space(14)
                safe = _pdf_safe_text(line)
                x = self.LEFT_MARGIN + indent
                self.pages_cmds[-1].append(
                    f"BT /F1 {font_size} Tf 0.18 0.22 0.28 rg {x} {self.y} Td ({safe}) Tj ET"
                )
                self.y -= 13
        self.y -= 3

    def add_bullet(self, label: str, detail: str = "") -> None:
        full = f"* {label}" + (f": {detail}" if detail else "")
        self.add_paragraph(full, font_size=9.5, indent=10)

    def build_bytes(self) -> bytes:
        # Stamp footers cleanly on every page
        total_pages = len(self.pages_cmds)
        for idx, cmds in enumerate(self.pages_cmds, 1):
            cmds.append(
                f"BT /F1 8 Tf 0.45 0.50 0.58 rg {self.LEFT_MARGIN} 28 Td "
                f"(Page {idx} of {total_pages} | Generated by TrustAudit | Not Formal Legal Advice) Tj ET"
            )

        objects: Dict[int, bytes] = {}
        # 1 = Catalog, 2 = Pages, 3 = F1 Helvetica, 4 = F2 Helvetica-Bold, 5 = Info
        objects[3] = b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>"
        objects[4] = b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>"
        objects[5] = f"<< /Title ({self.doc_title}) /Producer (TrustAudit PDF Engine) >>".encode("latin-1")

        page_obj_ids: List[int] = []
        next_id = 6
        for cmds in self.pages_cmds:
            stream_bytes = "\n".join(cmds).encode("latin-1", errors="replace")
            content_id = next_id
            page_id = next_id + 1
            next_id += 2
            objects[content_id] = (
                f"<< /Length {len(stream_bytes)} >>\nstream\n".encode("latin-1")
                + stream_bytes
                + b"\nendstream"
            )
            objects[page_id] = (
                f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {self.PAGE_W} {self.PAGE_H}] "
                f"/Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents {content_id} 0 R >>"
            ).encode("latin-1")
            page_obj_ids.append(page_id)

        kids_str = " ".join(f"{pid} 0 R" for pid in page_obj_ids)
        objects[2] = f"<< /Type /Pages /Kids [ {kids_str} ] /Count {len(page_obj_ids)} >>".encode("latin-1")
        objects[1] = b"<< /Type /Catalog /Pages 2 0 R >>"

        out = io.BytesIO()
        out.write(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
        offsets: Dict[int, int] = {}
        for obj_id in sorted(objects.keys()):
            offsets[obj_id] = out.tell()
            out.write(f"{obj_id} 0 obj\n".encode("latin-1"))
            out.write(objects[obj_id])
            out.write(b"\nendobj\n")

        xref_pos = out.tell()
        max_obj = max(objects.keys())
        out.write(f"xref\n0 {max_obj + 1}\n".encode("latin-1"))
        out.write(b"0000000000 65535 f \n")
        for obj_id in range(1, max_obj + 1):
            off = offsets.get(obj_id, 0)
            out.write(f"{off:010d} 00000 n \n".encode("latin-1"))
        out.write(
            f"trailer\n<< /Size {max_obj + 1} /Root 1 0 R /Info 5 0 R >>\nstartxref\n{xref_pos}\n%%EOF\n".encode("latin-1")
        )
        return out.getvalue()


def _gather_org_report_data(org_id: str) -> Dict[str, Any]:
    org = saas_store.get_organization(org_id) or {"id": org_id, "name": "Your Organisation", "plan": "starter"}
    profile = dpdp_store.get_onboarding_profile(org_id) or saas_store.get_org_profile(org_id) or {}
    company_name = profile.get("company_name") or org.get("name") or "Your Business"
    return {
        "org": org,
        "profile": profile,
        "company_name": company_name,
        "generated_at": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "setup_progress": dpdp_store.get_setup_progress(org_id),
        "attention_tasks": dpdp_store.get_home_attention_tasks(org_id, limit=5),
        "inventory": dpdp_store.get_data_inventory(org_id),
        "vendors": dpdp_store.get_vendors(org_id),
        "notices": dpdp_store.get_privacy_notices(org_id),
        "consents": dpdp_store.get_consent_records(org_id),
        "withdrawals": dpdp_store.get_withdrawal_requests(org_id),
        "requests": dpdp_store.get_rights_requests(org_id),
        "retention": dpdp_store.get_retention_schedules(org_id),
        "erasures": dpdp_store.get_erasure_tasks(org_id),
        "incidents": dpdp_store.get_breach_incidents(org_id),
        "scans": dpdp_store.get_website_scans(org_id),
        "evidence": dpdp_store.get_evidence_artifacts(org_id),
        "legacy_evidence": evidence_vault.list_evidence_for_org(org_id, framework="DPDP"),
    }


def generate_dpdp_pdf_report(org_id: str) -> bytes:
    """Generates a valid binary PDF readiness report strictly from stored org data."""
    d = _gather_org_report_data(org_id)
    pdf = PurePythonPDFBuilder(f"{d['company_name']} DPDP Readiness Report")

    pdf.add_heading(f"DPDP Readiness & Data Operations Summary - {d['company_name']}")
    pdf.add_paragraph(
        f"Organisation ID: {org_id} | Industry: {d['profile'].get('industry') or 'Not specified'} | "
        f"Generated: {d['generated_at']}"
    )
    pdf.add_paragraph(
        "Important Note: This report summarises operational records entered by your team and public website checks run in TrustAudit. "
        "Substantive business obligations under India's DPDP Act, 2023 (Sections 3-17) are scheduled to commence on 13 May 2027 "
        "(while institutional Board provisions commenced 13 Nov 2025 and Consent Manager registration commenced 13 Nov 2026). "
        "This report is not a government compliance certificate."
    )

    prog = d["setup_progress"]
    pdf.add_heading(f"1. Workspace Setup Progress ({prog['completed_count']} of {prog['total_steps']} Steps Completed)")
    for step in prog["steps"]:
        mark = "[DONE]" if step["completed"] else "[TODO]"
        pdf.add_bullet(f"{mark} {step['title']}")

    pdf.add_heading("2. Customer Data Summary")
    pdf.add_paragraph(f"Total Customer Data Records Listed: {len(d['inventory'])}")
    if d["inventory"]:
        for item in d["inventory"][:20]:
            pdf.add_bullet(
                item.get("category", "Record"),
                f"Purpose: {item.get('purpose', '')} | Basis: {item.get('legal_basis', '')} | Stored in: {item.get('storage_location', '')}",
            )
    else:
        pdf.add_paragraph("No customer data records added yet.")

    pdf.add_heading("3. Companies You Share Data With (Vendors & Contracts)")
    pdf.add_paragraph(f"Total Vendors Recorded: {len(d['vendors'])}")
    if d["vendors"]:
        for v in d["vendors"][:20]:
            pdf.add_bullet(
                v.get("name", "Vendor"),
                f"Service: {v.get('service', '')} | Agreement Status: {v.get('dpa_status', 'Not Started')} | Region: {v.get('storage_location', '')}",
            )
    else:
        pdf.add_paragraph("No software, lab, or service vendors recorded yet.")

    pdf.add_heading("4. Website Privacy Check Results")
    if d["scans"]:
        latest = d["scans"][0]
        metrics = latest.get("summary_metrics", {})
        pdf.add_paragraph(
            f"Latest Website Scanned: {latest.get('target_url', '')} on {latest.get('scanned_at', '')} "
            f"(Pages: {metrics.get('pages_scanned_count', 0)}, Forms: {metrics.get('forms_discovered_count', 0)}, "
            f"Observed Issues: {metrics.get('total_findings_count', 0)})"
        )
        for f in latest.get("findings", [])[:12]:
            if f.get("severity") != "INFORMATIONAL":
                pdf.add_bullet(f"[{f.get('severity')}] {f.get('title')}", f.get("observation", ""))
    else:
        pdf.add_paragraph("No website privacy scan has been run for this organisation yet.")

    pdf.add_heading("5. Privacy Notice, Consent, Requests, Retention & Incidents")
    pdf.add_bullet("Privacy Notices Saved", str(len(d["notices"])))
    pdf.add_bullet("Consent Records", f"{len(d['consents'])} recorded, {len(d['withdrawals'])} withdrawals logged")
    pdf.add_bullet("Customer Privacy Requests", f"{len(d['requests'])} requests logged")
    pdf.add_bullet("Retention & Deletion Rules", f"{len(d['retention'])} schedules, {len(d['erasures'])} erasure tasks")
    pdf.add_bullet("Privacy Incidents Logged", str(len(d["incidents"])))

    pdf.add_heading("6. Evidence Vault Inventory")
    pdf.add_paragraph(f"Total Evidence Items Stored: {len(d['evidence'])}")
    for ev in d["evidence"][:20]:
        pdf.add_bullet(
            f"{ev.get('title', 'Document')} ({ev.get('status', 'Uploaded')})",
            f"File: {ev.get('filename', '')} | Control: {ev.get('control_id', '')} | Hash: {str(ev.get('file_hash', ''))[:24]}...",
        )

    if d["attention_tasks"]:
        pdf.add_heading("7. Top Recommended Next Steps")
        for task in d["attention_tasks"]:
            pdf.add_bullet(task.get("title", "Task"), task.get("why", ""))

    return pdf.build_bytes()


